#!/bin/sh
# Rebuilds fonts.js, the copy of the font files in this folder that index.html
# reads when it's opened straight from disk (browsers won't let a file:// page
# read files next to it). Run it after adding or replacing a font:
#
#   sh fonts/bundle.sh
#
cd "$(dirname "$0")" || exit 1
{
  echo "// Generated by bundle.sh from the font files in this folder. Don't edit by hand."
  echo "window.PLANNER_FONT_FILES = {"
  for f in *.ttf *.otf *.TTF *.OTF; do
    [ -f "$f" ] || continue
    printf '  "%s": "' "$f"
    base64 < "$f" | tr -d '\n'
    printf '",\n'
  done
  echo "};"
} > fonts.js
echo "Wrote $(pwd)/fonts.js"
